"""Verify frozen local-baseline evidence and manuscript use; no fits or runs."""
import json
import re
from pathlib import Path

from local_baseline_validation import ROOT, OUT, PREFIX, digest, load, preflight, verify_hashes


def main():
    evidence_lock = load(ROOT / "paper/local_baseline_evidence_lock.json")
    verify_hashes(evidence_lock["source_sha256"])
    manifest = load(OUT / f"{PREFIX}_manifest.json")
    audit = load(OUT / f"{PREFIX}_audit.json")
    if manifest["source_sha256"] != preflight() or audit["source_sha256"] != manifest["source_sha256"]:
        raise ValueError("Local-baseline source lock differs")
    verify_hashes(manifest["output_sha256"])
    if audit["execution_sha256"] != manifest["output_sha256"] or audit["manifest_sha256"] != digest(OUT / f"{PREFIX}_manifest.json"):
        raise ValueError("Audited execution differs")
    if audit["status"] != "saved_models_audited_without_refitting" or audit["primary_clients"] != 300:
        raise ValueError("Complete saved-model audit required")
    if audit["maximum_reference_error_difference"] > 1e-10 or audit["maximum_relative_stationarity"] > 1e-5:
        raise ValueError("Saved-model numerical audit failed")
    numbers = audit["numerical_claims"]
    expected = "% Generated by local_baseline_validation.py --audit.\n" + "".join(
        f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(numbers.items()))
    if (ROOT / "paper/local_baseline_numbers.tex").read_text() != expected:
        raise ValueError("Local-baseline manuscript numbers differ")
    tex = (ROOT / "paper/main.tex").read_text()
    used = set(re.findall(r"\\((?:SmoothLocal|PriorResidual)[A-Za-z]+)", tex))
    required = set(numbers)-{"SmoothLocalStrength"}
    if not required <= used or not used <= set(numbers):
        raise ValueError(f"Local macro mismatch: missing={required-used}, unknown={used-set(numbers)}")
    if audit["selected_strength"] != 1e6 or "chosen: $10^6$" not in tex:
        raise ValueError("Reported selected penalty differs")
    figure = load(OUT / f"{PREFIX}_figure_manifest.json")
    if figure["audit_sha256"] != digest(OUT / f"{PREFIX}_audit.json") or figure["generator_sha256"] != digest(ROOT / "paper/plot_local_baseline.py"):
        raise ValueError("Smooth Local coverage figure provenance differs")
    verify_hashes(figure["output_sha256"])
    if "paper_identification_coverage_v3.pdf" not in tex:
        raise ValueError("Updated coverage figure missing")
    print(json.dumps(dict(status="verified", primary_fleets=10, clients=300,
                          numerical_claims=len(numbers), operation="read_only_no_fits_or_simulations")))


if __name__ == "__main__":
    main()
