"""Generate manuscript numbers from frozen fixed-speed results, without simulations."""
from pathlib import Path
import argparse
import json
import numpy as np
import pandas as pd
from prepare_oe_transient_figure import ROOT, original_digest, load, require

OUTPUT=ROOT/'paper/oe_transient_numbers.tex'


def build():
    manifest=load(ROOT/'results/tables/paper_oe_transient_benchmark_manifest.json')
    names=['results/tables/paper_oe_transient_benchmark_metrics.csv',
           'results/tables/paper_oe_transient_benchmark_summary.csv']
    for name in names:
        require(original_digest(ROOT/name)==manifest['outputs'][name],f'Changed evidence: {name}')
    frame=pd.read_csv(ROOT/names[0]);summary=pd.read_csv(ROOT/names[1])
    require(len(frame)==5400 and frame.status.eq('complete').all(),'Incomplete fixed-speed results')
    require(not frame.duplicated(['seed','client','method','speed_mps']).any(),'Duplicate result cases')
    methods={'NominalLTI':'Nominal','RestrictedLocal':'Restricted','SmoothLocal':'Smooth',
             'Global':'Global','Federated':'Fed','ExactLPV':'Exact'}
    lines=['% Generated by paper/prepare_oe_transient_numbers.py from committed results.']
    def macro(name,value):
        lines.append(r'\newcommand{\OETransient'+name+'}{'+str(value)+'}')
    for speed,tag in [(13,'Low'),(21,'Mid'),(29,'High')]:
        for method,name in methods.items():
            rows=frame[(frame.speed_mps==speed)&(frame.method==method)]
            require(len(rows)==300 and rows.groupby('seed').size().eq(30).all(),'Incomplete fleet')
            mean=float(rows.groupby('seed').tracking_rmse_deg_s.mean().mean())
            saved=summary[(summary.family=='all')&(summary.speed_mps==speed)&(summary.method==method)].iloc[0]
            np.testing.assert_allclose(mean,saved.tracking_rmse_deg_s,rtol=0,atol=1e-12)
            require(int(rows.feasible.sum())==saved.feasible,'Feasibility summary mismatch')
            macro(name+tag,f'{mean:.4f}')
            macro(name+tag+'Violations',int((~rows.feasible).sum()))
        paired=frame[frame.speed_mps==speed].groupby(['seed','method']).tracking_rmse_deg_s.mean().unstack()
        delta=paired.Global-paired.Federated
        macro('Global'+tag+'Absolute',f'{delta.mean():.5f}')
        macro('Global'+tag+'FleetWins',int((delta>0).sum()))
    for method,name in methods.items():
        rows=frame[frame.method==method]
        macro(name+'TotalViolations',int((~rows.feasible).sum()))
    good=frame[frame.method.isin(['NominalLTI','Global','Federated','ExactLPV'])]
    require(good.feasible.all() and good.limiter_fraction.eq(0).all(),'Successful-controller scope changed')
    macro('PeakAccelerationBound',f'{np.ceil(good.lateral_acceleration_peak_mps2.max()*100)/100:.2f}')
    macro('PeakSteeringBound',f'{np.ceil(good.steering_peak_deg.max()*100)/100:.2f}')
    return '\n'.join(lines)+'\n'


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true')
    args=parser.parse_args();text=build()
    if args.check:
        require(OUTPUT.read_text(encoding='utf-8')==text,'Manuscript numbers are stale')
    else:
        OUTPUT.write_text(text,encoding='utf-8',newline='\n')
    print(json.dumps(dict(status='verified' if args.check else 'generated',new_simulations=0)))
