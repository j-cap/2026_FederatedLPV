"""Generate Section VI numbers from audited, committed OE control results.

python paper/prepare_oe_control.py          # regenerate numbers and input manifest
python paper/prepare_oe_control.py --check  # verify without writing or simulating
"""
from pathlib import Path
import argparse
import hashlib
import json
import math

ROOT=Path(__file__).resolve().parents[1]
TABLES=ROOT/'results/tables'
NUMBERS=ROOT/'paper/oe_control_numbers.tex'
MANIFEST=TABLES/'paper_oe_control_manuscript_manifest.json'


def sha(path):
    value=path.read_bytes()
    if path.suffix in ['.json','.py','.tex']:value=value.replace(b'\r\n',b'\n')
    return hashlib.sha256(value).hexdigest()


def prepare():
    path=TABLES/'paper_oe_lqi_validation_analysis.json'
    analysis=json.loads(path.read_text(encoding='utf-8'))
    sources={str(path.relative_to(ROOT)):sha(path)}
    audit=analysis['audit']
    assert audit['status']=='passed' and audit['cases']==3600 and audit['clients']==300
    assert audit['outcomes']=={'complete':3600} and audit['synthesis_status']=={'designed':1800}
    cfg=ROOT/'code/config/paper_oe_lqi_validation.json'
    assert sha(cfg)==audit['protocol_sha256'];sources[str(cfg.relative_to(ROOT))]=sha(cfg)
    code=ROOT/'code/experiments/paper_oe_lqi_analysis.py'
    assert sha(code)==analysis['analysis_source_sha256'];sources[str(code.relative_to(ROOT))]=sha(code)
    rows=[]
    for name,expected in audit['result_file_sha256'].items():
        p=ROOT/name;assert sha(p)==expected;sources[name]=expected
        envelope=json.loads(p.read_text(encoding='utf-8'))
        payload=envelope['payload']
        canonical=json.dumps(payload,sort_keys=True,separators=(',',':'),allow_nan=False).encode()
        assert hashlib.sha256(canonical).hexdigest()==envelope['payload_sha256']
        for client in payload['clients']:
            for row in client['rows']:
                rows.append(dict(seed=payload['seed'],client=client['client'],family=client['family'],**row))
    numbers={}
    names={'NominalLTI':'Nominal','RestrictedLocal':'Restricted','SmoothLocal':'Smooth','Global':'Global','Federated':'Fed','ExactLPV':'Exact'}
    for item in analysis['summary']:
        m,s=item['method'],item['scenario'];tag=names[m]+s.capitalize()
        selected=[r['outcome'] for r in rows if (r['method'],r['scenario'])==(m,s)]
        assert len(selected)==300 and all(r['status']=='complete' for r in selected)
        mean=sum(r['metrics']['tracking_rmse_deg_s'] for r in selected)/300
        assert math.isclose(mean,item['fleet_rmse']['mean'],rel_tol=1e-12,abs_tol=1e-12)
        violations=sum(r['metrics']['beta_violation_samples']>0 for r in selected)
        assert violations==item['sideslip_violations']==300-item['feasible']
        numbers[tag]=f'{mean:.4f}'
        numbers[tag+'Violations']=str(violations)
        numbers[tag+'Median']=f"{item['metrics']['tracking_rmse_deg_s']['median']:.4f}"
    for item in analysis['pairs']:
        if item['baseline'] not in ['NominalLTI','Global']:continue
        assert item['complete_fleet_pairs']==10
        tag=names[item['baseline']]+item['scenario'].capitalize()
        numbers[tag+'Gain']=f"{item['paired_fleet_percent']['mean']:.2f}"
        numbers[tag+'Absolute']=f"{item['paired_fleet_absolute_deg_s']['mean']:.5f}"
        numbers[tag+'FleetWins']=str(item['fleet_wins'])
    for item in analysis['spectral']:
        tag=names[item['method']]
        numbers[tag+'Radius']=f"{item['radii']['max']:.4f}"
        numbers[tag+'Unstable']=str(item['at_least_one'])
    for family in ['handling','heavy']:
        for scenario in ['moderate','hard']:
            selected=[r for r in rows if r['family']==family and r['scenario']==scenario]
            fed={(r['seed'],r['client']):r['outcome']['metrics']['tracking_rmse_deg_s'] for r in selected if r['method']=='Federated'}
            baseline={(r['seed'],r['client']):r['outcome']['metrics']['tracking_rmse_deg_s'] for r in selected if r['method']=='Global'}
            assert len(fed)==100
            wins=sum(fed[k]<baseline[k] for k in fed)
            assert wins==(0 if family=='handling' else 100)
    text='% Generated by paper/prepare_oe_control.py; no fitting or simulation.\n'
    text+=''.join('\\newcommand{\\OECtrl'+k+'}{'+v+'}\n' for k,v in numbers.items())
    manifest=dict(version=1,execution_results_commit=analysis['execution_results_commit'],source_sha256=sources,
                  generator_sha256=sha(Path(__file__)),numbers_sha256=hashlib.sha256(text.encode()).hexdigest(),
                  claims=numbers,scope='Descriptive supporting control on reused OE confirmation fleets; all failed responses included.')
    return text,json.dumps(manifest,indent=2,allow_nan=False)+'\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    numbers,manifest=prepare()
    if args.check:
        assert NUMBERS.read_text(encoding='utf-8')==numbers,'Regenerate OE control numbers'
        assert MANIFEST.read_text(encoding='utf-8')==manifest,'Regenerate OE control manifest'
    else:
        NUMBERS.write_text(numbers,encoding='utf-8',newline='\n')
        MANIFEST.write_text(manifest,encoding='utf-8',newline='\n')
    print(json.dumps(dict(status='verified' if args.check else 'generated',claims=numbers.count('\\newcommand'),scientific_simulations=0)))


if __name__=='__main__':main()
